"""
R2-1, confound check (read-only): is "distance to the nearest training epitope"
confounded with "has this CDR3b been seen in training?"

The v2/sim negatives are generated by re-pairing CDR3bs that occur as positives
elsewhere in the pool. If an epitope-disjoint split then leaves most positive
CDR3bs inside training and most negative CDR3bs outside it, CDR3b training
membership alone carries label information, independently of any model.

Writes revision/evidence/r2_1_confound.json. Changes nothing else.
"""
import json

import numpy as np
import pandas as pd
import Levenshtein
from sklearn.metrics import roc_auc_score

V2 = 'data/splits_600_epitope_v2'
SIM = 'data/splits_600_epitope_sim'
PRED = 'results/baseline_rerun_v2/per_sample_predictions_v2.csv'
OUT = 'revision/evidence/r2_1_confound.json'
rep = {}

# ------------------------------------------------- 1. how negatives are built
print("=" * 78)
print("  1. WHERE DO THE NEGATIVE CDR3b COME FROM?")
print("=" * 78)
pool = pd.concat([pd.read_csv(f'{V2}/{k}.tsv', sep='\t') for k in ('train', 'val', 'test')],
                 ignore_index=True)
pos_cdr3 = set(pool.loc[pool.label == 1, 'cdr3'])
neg_cdr3 = set(pool.loc[pool.label == 0, 'cdr3'])
inside = neg_cdr3 & pos_cdr3
print(f"  pool rows {len(pool):,}  |  positive CDR3b {len(pos_cdr3):,}  "
      f"negative CDR3b {len(neg_cdr3):,}")
print(f"  negative CDR3b that ALSO occur as a positive somewhere in the pool: "
      f"{len(inside):,} / {len(neg_cdr3):,} ({100 * len(inside) / len(neg_cdr3):.1f}%)")
rep['pool'] = dict(rows=int(len(pool)), pos_cdr3=len(pos_cdr3), neg_cdr3=len(neg_cdr3),
                   neg_cdr3_also_positive=len(inside))

# ------------------------------------------------- 2. the trivial predictor
print("\n" + "=" * 78)
print("  2. A MODEL-FREE PREDICTOR: score = 1 if the CDR3b is NOT in train")
print("=" * 78)


def trivial(split):
    tr = pd.read_csv(f'{split}/train.tsv', sep='\t')
    te = pd.read_csv(f'{split}/test_balanced.tsv', sep='\t')
    seen = set(tr.cdr3)
    s = (~te.cdr3.isin(seen)).astype(float).values
    auc = roc_auc_score(te.label, s)
    print(f"  {split:34s} n={len(te):>6,}  ROC-AUC {auc:.4f}   "
          f"(CDR3b unseen: {s.mean():.1%} of rows)")
    return te, seen, float(auc)

te2, seen2, auc2 = trivial(V2)
_, _, aucS = trivial(SIM)
rep['trivial_cdr3_unseen_auc'] = dict(v2=auc2, sim=aucS)

# ------------------------------------------------- 3. cross-tabulation
print("\n" + "=" * 78)
print("  3. v2 TEST: distance bin x CDR3b-seen, with the positive rate in each cell")
print("=" * 78)
train_epi = sorted(set(pd.read_csv(f'{V2}/train.tsv', sep='\t')['antigen.epitope']))


def mind(e):
    return min(Levenshtein.distance(e, t) for t in train_epi)


dm = {e: mind(e) for e in te2['antigen.epitope'].unique()}
te2 = te2.assign(min_dist=te2['antigen.epitope'].map(dm),
                 cdr3_seen=te2.cdr3.isin(seen2))
te2['bin'] = np.where(te2.min_dist == 1, '1',
                      np.where(te2.min_dist == 2, '2',
                               np.where(te2.min_dist == 3, '3', '>=4')))
print(f"  {'bin':>5} {'CDR3b seen':>11} {'rows':>7} {'pos':>7} {'pos rate':>9}")
cells = []
for b in ('1', '2', '3', '>=4'):
    for s in (True, False):
        c = te2[(te2['bin'] == b) & (te2.cdr3_seen == s)]
        if not len(c):
            continue
        cells.append(dict(bin=b, cdr3_seen=bool(s), rows=int(len(c)),
                          pos=int(c.label.sum()), pos_rate=float(c.label.mean())))
        print(f"  {b:>5} {str(s):>11} {len(c):>7,} {int(c.label.sum()):>7,} "
              f"{c.label.mean():>8.1%}{'   <-- degenerate' if c.label.nunique() == 1 else ''}")
rep['v2_crosstab'] = cells
frac = te2.groupby('bin').cdr3_seen.mean()
print("\n  fraction of rows whose CDR3b was seen in training, by distance bin:")
for b in ('1', '2', '3', '>=4'):
    print(f"    distance {b:>3}: {frac[b]:.1%}")
rep['v2_cdr3_seen_fraction_by_bin'] = {b: float(frac[b]) for b in frac.index}

# ------------------------------------------------- 4. STEP within a fixed stratum
print("\n" + "=" * 78)
print("  4. STEP and DAISY on the one non-degenerate stratum at distance >=4")
print("=" * 78)
p = pd.read_csv(PRED)
p = p.merge(te2[['cdr3', 'antigen.epitope', 'min_dist', 'cdr3_seen', 'bin']].drop_duplicates(),
            on=['cdr3', 'antigen.epitope'], how='left')
sub = p[(p['bin'] == '>=4') & (p.cdr3_seen)]
row = dict(rows=int(len(sub)), pos=int(sub.label.sum()))
print(f"  distance >=4 AND CDR3b seen in training: n={len(sub):,} "
      f"({int(sub.label.sum())} pos / {int((sub.label == 0).sum())} neg)")
for m in ('STEP_seed42', 'STEP_ensemble', 'DAISY'):
    row[m] = float(roc_auc_score(sub.label, sub[m]))
    print(f"    {m:<16} ROC-AUC {row[m]:.4f}")
rep['v2_dist4plus_cdr3seen'] = row

json.dump(rep, open(OUT, 'w'), indent=2)
print(f"\nsaved {OUT}")
